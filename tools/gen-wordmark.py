#!/usr/bin/env python3
"""Generate the iMuninn wordmark SVGs from a real typeface (Inter Bold, SIL OFL).

    host/python/.venv/bin/python tools/gen-wordmark.py --font path/to/Inter-Bold.otf

Shapes the string with HarfBuzz (kerning applied), converts the glyph outlines to SVG paths,
and replaces the first i's dot with the app icon's red record ring (ring top on the cap line,
proportions from the icon). Writes docs/design/icons/imuninn-wordmark-{dark,light}.svg and the
copies under site/src/assets/. Colours come from docs/design/tokens.json (text / err).
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
TEXT = "ıMuninn"  # dotless i first: the ring is the dot


def shape(font_path: Path, text: str):
    blob = hb.Blob.from_file_path(font_path)
    face = hb.Face(blob)
    font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True})
    return list(zip(buf.glyph_infos, buf.glyph_positions)), face.upem


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True)
    ap.add_argument("--out", default=str(ROOT / "docs/design/icons"))
    a = ap.parse_args()
    font_path = Path(a.font)
    tt = TTFont(font_path)
    gs = tt.getGlyphSet()
    glyph_order = tt.getGlyphOrder()
    cap = tt["OS/2"].sCapHeight
    runs, upem = shape(font_path, TEXT)

    paths = []
    x = 0.0
    stem = None  # (centre x, width) of the first glyph's stem
    for i, (info, pos) in enumerate(runs):
        name = glyph_order[info.codepoint]
        g = gs[name]
        pen = SVGPathPen(gs)
        g.draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))  # flip y
        d = pen.getCommands()
        if d:
            paths.append(d)
        if i == 0:
            bp = BoundsPen(gs)
            g.draw(bp)
            x0, _, x1, _ = bp.bounds
            stem = (x + (x0 + x1) / 2, x1 - x0)
        x += pos.x_advance
    width = x
    cx, sw = stem
    outer, ring_w, dot = 0.78 * sw, 0.13 * sw, 0.42 * sw   # ring as wide as the typeface's own i-dot
    cy = -(cap - outer - ring_w / 2)   # ring top on the cap line
    # tight box: a margin of 6% of the cap height around ink; y runs from -(cap + ring) to the descender-less baseline
    m = 0.06 * cap
    top = cy - outer - ring_w / 2 - m
    bottom = 0.02 * cap + m
    vb = f"{-m:.0f} {top:.0f} {width + 2 * m:.0f} {bottom - top:.0f}"

    tok = json.load(open(ROOT / "docs/design/tokens.json"))["color"]
    for theme in ("dark", "light"):
        ink, red = tok["text"][theme]["hex"], tok["err"][theme]["hex"]
        svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="iMuninn">',
               f'  <!-- iMuninn wordmark: {font_path.name} outlines (SIL OFL), first i dot replaced by the record ring. tokens: text / err. Generated by tools/gen-wordmark.py -->',
               f'  <path fill="{ink}" fill-rule="nonzero" d="{" ".join(paths)}"/>',
               f'  <circle cx="{cx:.1f}" cy="{cy:.1f}" r="{outer - ring_w / 2:.1f}" fill="none" stroke="{red}" stroke-width="{ring_w:.1f}"/>',
               f'  <circle cx="{cx:.1f}" cy="{cy:.1f}" r="{dot:.1f}" fill="{red}"/>',
               "</svg>", ""]
        out = Path(a.out) / f"imuninn-wordmark-{theme}.svg"
        out.write_text("\n".join(svg))
        shutil.copy(out, ROOT / "site/src/assets" / f"wordmark-{theme}.svg")
        print("wrote", out)


if __name__ == "__main__":
    main()
