#!/usr/bin/env python3
"""Generate the reference pages that are committed under docs/ (CI checks they are current).

    host/python/.venv/bin/python tools/gen-docs.py          # writes:
      docs/python/07-cli.md        from the argparse parser in imuninn.cli
      docs/python/08-api.md        from the docstrings of the public API (griffe, static)
      docs/protocol/messages.md    from protocol/imuninn.proto (messages, enums, fields, comments)

Run it after changing cli.py, public docstrings or the .proto. English only; the docs site
serves these pages in both locales.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY_SRC = ROOT / "host/python/src"
sys.path.insert(0, str(PY_SRC))

HEADER = "<!-- GENERATED by tools/gen-docs.py — do not edit by hand. -->\n\n"


# ----------------------------------------------------------------------------- CLI

def gen_cli() -> str:
    from imuninn.cli import build_parser  # type: ignore

    parser = build_parser()
    out = [HEADER, "# CLI reference\n\n", "Every command that talks to a phone takes an optional `target`: a Bonjour name, "
           "an IP, or `ip:port`; without it the first phone found is used.\n\n",
           "```\n", parser.format_usage().strip(), "\n```\n\n"]
    subs = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    for name, sp in subs.choices.items():
        out.append(f"## imuninn {name}\n\n")
        out.append(f"{sp.description or subs._choices_actions[[c.dest for c in subs._choices_actions].index(name)].help}\n\n")
        out.append("```\n" + sp.format_help().strip() + "\n```\n\n")
        nested = [a for a in sp._actions if isinstance(a, argparse._SubParsersAction)]
        for n in nested:
            for sub_name, ssp in n.choices.items():
                out.append(f"### imuninn {name} {sub_name}\n\n```\n{ssp.format_help().strip()}\n```\n\n")
    out.append("## imuninn-mcp\n\nStarts the MCP server (stdio). Tools and setup: [MCP](../agents/MCP.md).\n")
    return "".join(out)


# ----------------------------------------------------------------------------- API

PUBLIC = [
    ("imuninn", ["discover", "connect", "Device", "Phone", "LeaseError", "PROTOCOL_VERSION", "SERVICE_TYPE", "DEFAULT_CONTROL_PORT"]),
    ("imuninn.session", ["Device", "connect"]),
    ("imuninn.discovery", ["Phone", "discover", "resolve"]),
    ("imuninn.client", ["PhoneClient", "StreamStats", "LeaseError"]),
    ("imuninn.depth", None),
    ("imuninn.video", ["H264Decoder"]),
    ("imuninn.mcap_io", ["McapRecorder", "replay", "convert", "summary"]),
    ("imuninn.profiles", ["builtin_profiles", "load", "to_patch", "from_config", "dump", "resolve_path"]),
]


def _doc(obj) -> str:
    d = obj.docstring.value if obj.docstring else ""
    # reST roles -> plain code; "::" literal-block markers -> ":" (the indented block is code in Markdown too)
    d = re.sub(r":(?:class|meth|func|attr|mod):`~?([^`]+)`", lambda m: "`" + m.group(1).split(".")[-1] + "`", d)
    d = d.replace("::\n", ":\n")
    return d.strip()


def _sig(fn) -> str:
    params = []
    for p in fn.parameters:
        if p.name in ("self", "cls"):
            continue
        s = p.name
        if p.annotation is not None:
            s += f": {p.annotation}"
        if p.default is not None:
            s += f" = {p.default}"
        params.append(s)
    ret = f" -> {fn.returns}" if fn.returns is not None else ""
    prefix = "async " if "async" in getattr(fn, "labels", set()) else ""
    return f"{prefix}def {fn.name}({', '.join(params)}){ret}"


def gen_api() -> str:
    import griffe

    pkg = griffe.load("imuninn", search_paths=[str(PY_SRC)])
    out = [HEADER, "# API reference\n\n",
           "Public API of the `imuninn` package, generated from the docstrings. Start with "
           "`imuninn.connect()` / `imuninn.Device`; everything else is for specific tasks.\n\n"]
    for modname, names in PUBLIC:
        mod = pkg if modname == "imuninn" else pkg
        for part in modname.split(".")[1:]:
            mod = mod[part]
        out.append(f"## `{modname}`\n\n")
        if _doc(mod):
            out.append(_doc(mod).split("\n\n")[0] + "\n\n")
        members = names if names is not None else [n for n, m in mod.members.items()
                                                     if not n.startswith("_") and not m.is_alias and (m.is_function or m.is_class)]
        if modname == "imuninn":
            out.append("Re-exported for convenience: `discover`, `connect`, `Device`, `Phone`, `LeaseError` (documented in their modules below).\n\n")
        for name in members:
            m = mod.members.get(name)
            if m is None or m.is_alias:
                continue
            if m.is_attribute:
                out.append(f"- `{name}` = `{m.value}`\n")
                continue
            out.append(f"### `{name}`\n\n")
            if m.is_class:
                out.append(f"```python\nclass {name}\n```\n\n")
                if _doc(m):
                    out.append(_doc(m) + "\n\n")
                init = m.members.get("__init__")
                if init is not None and init.is_function and _doc(init):
                    out.append(f"```python\n{_sig(init)}\n```\n\n{_doc(init)}\n\n")
                for mn, mm in m.members.items():
                    is_prop = mm.is_attribute and "property" in getattr(mm, "labels", set())
                    if mn.startswith("_") or not (mm.is_function or is_prop):
                        continue
                    if mm.is_function:
                        out.append(f"#### `{name}.{mn}`\n\n```python\n{_sig(mm)}\n```\n\n")
                    else:
                        ann = f" -> {mm.annotation}" if mm.annotation is not None else ""
                        out.append(f"#### `{name}.{mn}` (property{ann})\n\n")
                    if _doc(mm):
                        out.append(_doc(mm) + "\n\n")
            elif m.is_function:
                out.append(f"```python\n{_sig(m)}\n```\n\n")
                if _doc(m):
                    out.append(_doc(m) + "\n\n")
        out.append("\n")
    return "".join(out)


# ----------------------------------------------------------------------------- proto

def gen_proto() -> str:
    text = (ROOT / "protocol/imuninn.proto").read_text()
    version = (ROOT / "protocol/VERSION").read_text().strip()
    out = [HEADER, f"# Protocol messages (v{version})\n\n",
           "Generated from `protocol/imuninn.proto`. Comments are the ones in the file; the "
           "[protocol spec](../../protocol/README.md) explains the flow, the raw file is "
           "[imuninn.proto](proto.md).\n\n"]
    # crude but sufficient parser: top-level and nested messages / enums with trailing comments
    lines = text.splitlines()
    i = 0
    stack: list[tuple[str, str]] = []  # (kind, name)
    pending_comment: list[str] = []
    rows: list[tuple[str, str, str]] = []

    def flush():
        pass

    while i < len(lines):
        raw = lines[i].rstrip()
        s = raw.strip()
        i += 1
        if not s:
            pending_comment = []
            continue
        if s.startswith("//"):
            pending_comment.append(s.lstrip("/ ").strip())
            continue
        m = re.match(r"(message|enum)\s+(\w+)\s*\{", s)
        if m:
            kind, name = m.group(1), m.group(2)
            full = ".".join([n for _, n in stack] + [name])
            desc = " ".join(pending_comment)
            pending_comment = []
            stack.append((kind, full))
            out.append(f"{'#' * min(2 + len(stack), 4)} `{full}` ({kind})\n\n")
            if desc:
                out.append(desc + "\n\n")
            out.append("| field | type | # | notes |\n| --- | --- | --- | --- |\n" if kind == "message" else "| value | # | notes |\n| --- | --- | --- |\n")
            continue
        if s.startswith("}"):
            if stack:
                stack.pop()
            out.append("\n")
            pending_comment = []
            continue
        if s.startswith("oneof ") or s.startswith("reserved"):
            out.append(f"| *{s.rstrip('{').strip()}* | | | |\n" if stack and stack[-1][0] == "message" else "")
            continue
        comment = ""
        if "//" in s:
            s, comment = s.split("//", 1)
            s, comment = s.strip(), comment.strip()
        if pending_comment:
            comment = (" ".join(pending_comment) + (" " + comment if comment else "")).strip()
            pending_comment = []
        if not stack:
            continue
        kind = stack[-1][0]
        if kind == "message":
            m = re.match(r"(repeated\s+|optional\s+)?(map<[^>]+>|[\w.]+)\s+(\w+)\s*=\s*(\d+)", s)
            if m:
                label = (m.group(1) or "").strip()
                typ = f"{label} {m.group(2)}".strip()
                out.append(f"| `{m.group(3)}` | `{typ}` | {m.group(4)} | {comment} |\n")
        else:
            m = re.match(r"(\w+)\s*=\s*(-?\d+)", s)
            if m:
                out.append(f"| `{m.group(1)}` | {m.group(2)} | {comment} |\n")
    return "".join(out)


def main() -> None:
    (ROOT / "docs/python/07-cli.md").write_text(gen_cli())
    (ROOT / "docs/python/08-api.md").write_text(gen_api())
    (ROOT / "docs/protocol").mkdir(exist_ok=True)
    (ROOT / "docs/protocol/messages.md").write_text(gen_proto())
    print("wrote docs/python/07-cli.md, docs/python/08-api.md, docs/protocol/messages.md")


if __name__ == "__main__":
    main()
