#!/usr/bin/env python3
"""docs/design/tokens.json -> mobile/src/ui/tokens.ts (hex per theme, OKLCH in comments).
React Native cannot parse oklch(), so the app uses the hex conversions from the same file."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
tok = json.load(open(root / "docs/design/tokens.json"))["color"]
names = {"bg": "bg", "card": "card", "cardAlt": "card-alt", "text": "text", "muted": "muted", "border": "border",
         "accent": "accent", "accentFill": "accent-fill", "onAccent": "on-accent", "ok": "ok", "warn": "warn",
         "warnSurface": "warn-surface", "onWarn": "on-warn", "warnText": "warn-text", "err": "err", "dangerFill": "danger-fill"}
out = ["// GENERATED by tools/gen-theme.py from docs/design/tokens.json — do not edit by hand.", ""]
for theme in ("dark", "light"):
    out.append(f"export const {theme} = {{")
    for js, key in names.items():
        out.append(f'  {js}: "{tok[key][theme]["hex"]}",'.ljust(26) + f' // {tok[key][theme]["oklch"]}')
    out += ['  previewBg: "#000000",      // preview box, both themes',
            '  scrim: "rgba(0,0,0,0.45)", // preview overlay; text on it is always dark `text`',
            "};", ""]
out.append("export type Colors = typeof dark;")
(root / "mobile/src/ui/tokens.ts").write_text("\n".join(out) + "\n")
print("wrote mobile/src/ui/tokens.ts")
